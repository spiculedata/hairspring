#!/bin/sh
# record-build.sh <output file>: writes the BUILD-RECORD of the current build (native macOS arm; one "arm").
# Refuses to overwrite an existing file, and stops if the SDK tree is not the pinned one or has local changes.
# Run `make condlock tprobe selftest-bins` first.
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
out=${1:?usage: record-build.sh <output file>}
build=${CL_BUILD:-$here/build}

if [ -e "$out" ]; then
  echo "record-build.sh: refusing to overwrite existing $out" >&2
  exit 1
fi

pin() { grep "^$1=" "$here/PINS" | cut -d= -f2; }
sdk_commit=$(pin SDK_COMMIT)
sdk_tree=$(pin SDK_TREE)

# The pinned commit must exist, hold the pinned tree, and the working tree's sdks/c must be exactly that tree.
[ "$(git -C "$here" rev-parse "$sdk_commit:sdks/c")" = "$sdk_tree" ] ||
  { echo "record-build.sh: $sdk_commit:sdks/c is not tree $sdk_tree" >&2; exit 1; }
[ "$(git -C "$here" rev-parse HEAD:sdks/c)" = "$sdk_tree" ] ||
  { echo "record-build.sh: HEAD:sdks/c differs from the pinned tree $sdk_tree" >&2; exit 1; }
[ -z "$(git -C "$here" status --porcelain -- ../../sdks/c)" ] ||
  { echo "record-build.sh: sdks/c has local changes" >&2; exit 1; }

sha() { shasum -a 256 "$1" | awk '{ print $1 }'; }

{
  echo "# Generated by scripts/record-build.sh. Do not edit. Native macOS build, informational (not glibc, not the engine)."
  echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "host: $(uname -sm), $(sw_vers -productName) $(sw_vers -productVersion)"
  echo "compiler: $(cc --version | head -n 1)"
  echo "flags: -std=gnu11 -O2 -g -Wall -Wextra -Werror -pthread"
  echo
  echo "[source]"
  echo "git HEAD: $(git -C "$here" rev-parse HEAD)"
  echo "origin/main base of the worktree: $sdk_commit"
  echo "sdks/c commit (pin): $sdk_commit"
  echo "sdks/c tree  (pin): $sdk_tree"
  echo "sdks/c tree  (HEAD): $(git -C "$here" rev-parse HEAD:sdks/c)"
  echo "examples/glibc-condlock changed paths: $(git -C "$here" status --porcelain -- . ':!results' | wc -l | tr -d ' ')"
  echo
  echo "[sources]"
  (cd "$here" && for f in PINS Makefile $(find src tests scripts -type f | sort); do echo "$(sha "$f")  $f"; done)
  echo
  echo "[libhairspring.a] (one arm: macOS; each glibc arm gets its own, built against that arm's headers)"
  echo "$(sha "$build/sdk/libhairspring.a")  sdk/libhairspring.a"
  echo
  echo "[binaries]"
  for b in condlock tprobe condlock-novio condlock-nowd; do echo "$(sha "$build/$b")  $b"; done
  for p in "$build"/planted/condlock-*; do
    case $p in *.dSYM) continue ;; esac
    echo "$(sha "$p")  planted/$(basename "$p")"
  done
} >"$out"
echo "wrote $out"
