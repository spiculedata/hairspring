#!/bin/sh
# summarize-selftests.sh <results dir>: reads the per-run .class/.out files and writes <results dir>/SUMMARY.txt.
# Verdicts follow the pre-registered criteria; every number comes from the raw files next to it.
set -eu

res=${1:?usage: summarize-selftests.sh <results dir>}
sum=$res/SUMMARY.txt

# count_class <cell dir> <class> [extra grep pattern on the class line]
count_class() {
  n=0
  for f in "$1"/run-*.class; do
    if grep -q "^class=$2 " "$f" && grep -q -- "${3:-.}" "$f"; then n=$((n + 1)); fi
  done
  echo "$n"
}

# hist <cell dir>: class histogram, one class per run file
hist() {
  for f in "$1"/run-*.class; do tr ' ' '\n' <"$f" | grep '^class=' | head -n 1 | cut -d= -f2; done | sort | uniq -c |
    awk '{ printf "%s=%s ", $2, $1 } END { print "" }'
}

mean_ticks() { # mean ticks= and max maxstag= over a cell's stdout lines
  for f in "$1"/run-*.out; do cat "$f"; done | awk '
    { for (i = 1; i <= NF; i++) { if ($i ~ /^ticks=/) { v = $i; sub(/ticks=/, "", v); if (v == "") { v = $(i + 1) } t += v; n++ }
        if ($i ~ /^maxstag=/) { w = $i; sub(/maxstag=/, "", w); if (w == "") { w = $(i + 1) } if (w + 0 > m) m = w + 0 } } }
    END { if (n == 0) { print "0 0 0" } else { printf "%.2f %d %d\n", t / n, m, n } }'
}

zero_bound() { awk -v n="$1" 'BEGIN { if (n > 0) printf "%.3f%%", 100 * (1 - exp(log(0.05) / n)); else print "n/a" }'; }

{
  echo "condlock Mac self-tests: SUMMARY"
  echo "Label: on macOS, not glibc, not this engine. Informational evidence; nothing here tunes Q, T or Delta."
  echo "Generated by scripts/summarize-selftests.sh from the raw run files in this directory."
  echo

  if [ -d "$res/dpos" ]; then
    d=$res/dpos
    runs=$(find "$d" -name 'run-*.class' | wc -l | tr -d ' ')
    applied=$(count_class "$d" HIT 'applied=1')
    applied_all=0
    applied_not_hit=0
    for f in "$d"/run-*.class; do
      if grep -q 'applied=1' "$f"; then
        applied_all=$((applied_all + 1))
        grep -q '^class=HIT ' "$f" || applied_not_hit=$((applied_not_hit + 1))
      fi
    done
    echo "== D-pos (planted drop-signal; must fire in every run where it applied)"
    echo "runs: $runs   applied=1: $applied_all   applied=1 and class HIT: $applied   applied=1 but not HIT: $applied_not_hit"
    echo "classes: $(hist "$d")"
    awk -v a="$applied_all" -v r="$runs" 'BEGIN { printf "applied share: %.1f%% (needs >= 95%%)\n", (r ? 100 * a / r : 0) }'
    echo "applied=1 runs that did not fire:"
    for f in "$d"/run-*.class; do
      if grep -q 'applied=1' "$f" && ! grep -q '^class=HIT ' "$f"; then echo "  $(basename "$f" .class): $(cat "$f")"; fi
    done
    verdict=FAIL
    share_ok=$(awk -v a="$applied_all" -v r="$runs" 'BEGIN { print (r > 0 && a / r >= 0.95) ? 1 : 0 }')
    if [ "$applied_not_hit" -eq 0 ] && [ "$share_ok" = 1 ] && [ "$applied_all" -gt 0 ]; then verdict=PASS; fi
    echo "D-pos verdict: $verdict"
    echo
  fi

  if [ -d "$res/dneg" ]; then
    d=$res/dneg
    runs=$(find "$d" -name 'run-*.class' | wc -l | tr -d ' ')
    nohit=$(count_class "$d" NOHIT)
    firing=$(($(count_class "$d" HIT) + $(count_class "$d" STALL)))
    ticks_line=$(mean_ticks "$d")
    mean=$(echo "$ticks_line" | cut -d' ' -f1)
    maxstag=$(echo "$ticks_line" | cut -d' ' -f2)
    echo "== D-neg (healthy counted build; 0 firings of the property and of STALL)"
    echo "runs: $runs   NOHIT: $nohit   firings (HIT + STALL): $firing   other classes: $((runs - nohit - firing))"
    echo "classes: $(hist "$d")"
    echo "mean watchdog ticks per run: $mean (non-vacuity precondition: >= 3)   max stagnant ticks seen in any run: $maxstag (Q = 10)"
    echo "exact zero bound for 0 of $runs: $(zero_bound "$runs")"
    pre=$(awk -v m="$mean" 'BEGIN { print (m >= 3) ? 1 : 0 }')
    verdict=FAIL
    if [ "$pre" != 1 ]; then
      verdict="VACUOUS (mean ticks below 3: the watchdog barely evaluated)"
    elif [ "$firing" -eq 0 ] && [ "$nohit" -eq "$runs" ]; then
      verdict=PASS
    elif [ "$firing" -eq 0 ]; then
      verdict="NOT-PASS (no firing, but $((runs - nohit)) run(s) outside NOHIT: see classes)"
    fi
    echo "D-neg verdict: $verdict"
    echo
  fi

  for cellname in leak:L barrier:B holdg:M; do
    plant=${cellname%%:*}
    want=${cellname##*:}
    d=$res/dstall-$plant
    [ -d "$d" ] || continue
    runs=$(find "$d" -name 'run-*.class' | wc -l | tr -d ' ')
    applied_all=0
    stall_ok=0
    prop_fired=0
    wrong_sub=0
    for f in "$d"/run-*.class; do
      grep -q 'applied=1' "$f" || continue
      applied_all=$((applied_all + 1))
      if grep -q '^class=STALL ' "$f"; then stall_ok=$((stall_ok + 1)); fi
      if grep -q 'prop_false=1' "$f"; then prop_fired=$((prop_fired + 1)); fi
      if grep -q '^class=STALL ' "$f" && ! grep -q "subtype=$want " "$f"; then wrong_sub=$((wrong_sub + 1)); fi
    done
    echo "== D-stall, plant $plant (must end in STALL, subtype $want, property site true)"
    echo "runs: $runs   applied=1: $applied_all   applied and STALL: $stall_ok   property fired: $prop_fired   STALL with subtype other than $want: $wrong_sub"
    echo "classes: $(hist "$d")"
    verdict=FAIL
    if [ "$applied_all" -gt 0 ] && [ "$stall_ok" -eq "$applied_all" ] && [ "$prop_fired" -eq 0 ] && [ "$wrong_sub" -eq 0 ]; then verdict=PASS; fi
    echo "D-stall ($plant) verdict: $verdict"
    echo
  done
} >"$sum"
