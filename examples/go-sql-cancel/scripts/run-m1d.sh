#!/bin/sh
# M1d: native macOS (darwin/arm64) runs of the sqlcancel workload on the three toolchains, with and without -race.
# Informational only: "on macOS, not this engine". Raw outputs are kept as files:
#
#   results/m1d/MANIFEST                          host, toolchain versions, sha256 of every binary run
#   results/m1d/<toolchain>/<cell>/run-NN.{out,err,exit}   stdout, stderr and exit status of every run
#   results/m1d/<toolchain>/race-build.txt        the -race build output (a failed build is a NOT-RUN cell)
#
# Cells: native-yield-gmp2, native-yield-gmpdef, native-std-gmp2, native-std-gmpdef, race-std, race-yield.
# gmp2 sets GOMAXPROCS=2; gmpdef leaves it unset (one P per core). Run scripts/fetch-go.sh and
# scripts/build-patched-toolchain.sh first; summarise with scripts/summarize-m1d.sh.
#
#   scripts/run-m1d.sh            RUNS_YIELD, RUNS_STD, RUNS_RACE, Q_STD, Q_YIELD, Q_RACE_STD override the sizes
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
tc="$here/.cache/toolchains"
bin="$here/build/m1d-bin"
res=${M1D_RESULTS:-$here/results/m1d}
toolchains="go1.24.5 go1.24.6 go1.24.5-fixonly"

runs_yield=${RUNS_YIELD:-20}
runs_std=${RUNS_STD:-5}
runs_race=${RUNS_RACE:-10}
q_std=${Q_STD:-25000}
q_yield=${Q_YIELD:-100}
q_race_std=${Q_RACE_STD:-250}

# Results are evidence: never write into an existing output directory (an earlier run was lost to an overwrite).
# Choose a new directory with M1D_RESULTS=<path>, or move the old one away yourself.
if [ -e "$res" ]; then
  echo "run-m1d.sh: refusing to write into existing $res (set M1D_RESULTS to a new directory)" >&2
  exit 1
fi

sha() { shasum -a 256 "$1" | awk '{ print $1 }'; }

# build <toolchain> <cgo 0|1> <extra go build flag or empty> <dest>; returns go's status
build() {
  mkdir -p "$(dirname "$4")"
  (
    cd "$here"
    env -i HOME="$HOME" PATH="/usr/bin:/bin:/usr/sbin:/sbin" \
      GOROOT="$tc/$1" GOTOOLCHAIN=local GOPROXY=off GOFLAGS= GOCACHE="$here/build/gocache-m1d-$1" \
      CGO_ENABLED="$2" GOOS=darwin GOARCH=arm64 \
      "$tc/$1/bin/go" build -trimpath -buildvcs=false ${3:+"$3"} -o "$4" ./cmd/sqlcancel
  )
}

# run_cell <toolchain> <cell> <binary> <gomaxprocs or empty> <runs> <args...>
run_cell() {
  t=$1; cell=$2; binary=$3; gmp=$4; n=$5; shift 5
  d="$res/$t/$cell"
  mkdir -p "$d"
  i=1
  while [ "$i" -le "$n" ]; do
    num=$(printf '%02d' "$i")
    code=0
    env -i HOME="$HOME" PATH="/usr/bin:/bin" ${gmp:+GOMAXPROCS="$gmp"} \
      "$binary" "$@" >"$d/run-$num.out" 2>"$d/run-$num.err" || code=$?
    echo "$code" >"$d/run-$num.exit"
    i=$((i + 1))
  done
  echo "$t $cell: $n runs"
}

mkdir -p "$res"
{
  echo "M1d manifest (generated by scripts/run-m1d.sh; informational, race detector on macOS, not this engine)"
  echo "date: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "host: $(uname -sm), $(sw_vers -productName) $(sw_vers -productVersion), ncpu $(sysctl -n hw.ncpu)"
  echo "sizes: runs_yield=$runs_yield runs_std=$runs_std runs_race=$runs_race q_std=$q_std q_yield=$q_yield q_race_std=$q_race_std"
  echo "source: git $(git -C "$here" rev-parse --short HEAD), working tree $(git -C "$here" status --porcelain -- . ':!results' | wc -l | tr -d ' ') changed paths under examples/go-sql-cancel"
} >"$res/MANIFEST"

for t in $toolchains; do
  mkdir -p "$res/$t"
  echo "toolchain $t: $(GOROOT="$tc/$t" GOTOOLCHAIN=local "$tc/$t/bin/go" version)" >>"$res/MANIFEST"

  build "$t" 0 "" "$bin/$t/sqlcancel"
  echo "  $(sha "$bin/$t/sqlcancel")  $t native (darwin/arm64, CGO_ENABLED=0)" >>"$res/MANIFEST"
  run_cell "$t" native-yield-gmp2 "$bin/$t/sqlcancel" 2 "$runs_yield" -mode=yield -q="$q_yield"
  run_cell "$t" native-yield-gmpdef "$bin/$t/sqlcancel" "" "$runs_yield" -mode=yield -q="$q_yield"
  run_cell "$t" native-std-gmp2 "$bin/$t/sqlcancel" 2 "$runs_std" -mode=std -q="$q_std"
  run_cell "$t" native-std-gmpdef "$bin/$t/sqlcancel" "" "$runs_std" -mode=std -q="$q_std"

  # -race needs cgo and the race runtime; if the build fails the cells are NOT-RUN and the output says why.
  race_status=0
  build "$t" 1 -race "$bin/$t/sqlcancel-race" >"$res/$t/race-build.txt" 2>&1 || race_status=$?
  echo "build exit status: $race_status" >>"$res/$t/race-build.txt"
  if [ "$race_status" -eq 0 ]; then
    echo "  $(sha "$bin/$t/sqlcancel-race")  $t race (darwin/arm64, CGO_ENABLED=1 -race)" >>"$res/MANIFEST"
    run_cell "$t" race-std "$bin/$t/sqlcancel-race" "" "$runs_race" -mode=std -q="$q_race_std"
    run_cell "$t" race-yield "$bin/$t/sqlcancel-race" "" "$runs_race" -mode=yield -q="$q_yield"
  else
    echo "  NOT-RUN  $t race (build failed, see $t/race-build.txt)" >>"$res/MANIFEST"
    echo "$t race: NOT-RUN, build failed"
  fi
done
