#!/bin/sh
# Build the hello programs with each toolchain (twice each, static linux/amd64) and write BUILD-RECORD: the sha256 of
# every toolchain input and every built binary. Fails if a pair of builds differs.
#
#   scripts/record-hashes.sh            writes BUILD-RECORD next to PINS
#
# Run scripts/fetch-go.sh and scripts/build-patched-toolchain.sh first. The environment is cleaned: GOTOOLCHAIN=local,
# GOPROXY=off, no cgo, and the same flags for every binary.
set -eu

here=$(cd "$(dirname "$0")/.." && pwd)
tc="$here/.cache/toolchains"
out="$here/build"
record="$here/BUILD-RECORD"
toolchains="go1.24.5 go1.24.6 go1.24.5-fixonly"
programs="hello hellosql"

sha() { shasum -a 256 "$1" | awk '{ print $1 }'; }

# Digest of a directory tree: sha256 over the sorted "sha256  relative-path" lines of its files.
tree_digest() {
  (cd "$1" && find . -type f | LC_ALL=C sort | while IFS= read -r f; do printf '%s  %s\n' "$(sha "$f")" "$f"; done) |
    shasum -a 256 | awk '{ print $1 }'
}

build_one() {
  tcname=$1
  prog=$2
  dest=$3
  mkdir -p "$(dirname "$dest")"
  (
    cd "$here"
    env -i HOME="$HOME" PATH="/usr/bin:/bin" \
      GOROOT="$tc/$tcname" GOTOOLCHAIN=local GOPROXY=off GOFLAGS= GOCACHE="$out/gocache-$tcname" \
      CGO_ENABLED=0 GOOS=linux GOARCH=amd64 GOAMD64=v1 \
      "$tc/$tcname/bin/go" build -trimpath -buildvcs=false -ldflags=-buildid= -o "$dest" "./cmd/$prog"
  )
}

pin_for() { awk -v f="$1" '$2 == f { print $1 }' "$here/PINS"; }

status=0
{
  echo "# Generated by scripts/record-hashes.sh. Do not edit. Host: $(uname -sm). Bootstrap: official go1.24.5 darwin-arm64."
  echo "# Binaries: CGO_ENABLED=0 GOOS=linux GOARCH=amd64 GOAMD64=v1 go build -trimpath -buildvcs=false -ldflags=-buildid="
  echo
  echo "[archives]  (official, from PINS; verified against go.dev)"
  for f in go1.24.5.darwin-arm64.tar.gz go1.24.6.darwin-arm64.tar.gz go1.24.5.linux-amd64.tar.gz go1.24.6.linux-amd64.tar.gz go1.24.5.src.tar.gz go1.24.6.src.tar.gz; do
    echo "$(pin_for "$f")  $f"
  done
  echo
  echo "[patch]"
  echo "$(sha "$here/patches/fix-only.patch")  patches/fix-only.patch"
  echo
  for t in $toolchains; do
    echo "[toolchain $t]"
    echo "$(sha "$tc/$t/bin/go")  bin/go (darwin-arm64)"
    echo "$(sha "$tc/$t/pkg/tool/darwin_arm64/compile")  pkg/tool/darwin_arm64/compile"
    echo "$(sha "$tc/$t/pkg/tool/darwin_arm64/link")  pkg/tool/darwin_arm64/link"
    echo "$(sha "$tc/$t/src/database/sql/sql.go")  src/database/sql/sql.go"
    echo "$(sha "$tc/$t/src/database/sql/convert.go")  src/database/sql/convert.go"
    echo "$(tree_digest "$tc/$t/src/database/sql")  tree src/database/sql"
    for p in $programs; do
      build_one "$t" "$p" "$out/$t/a/$p"
      build_one "$t" "$p" "$out/$t/b/$p"
      a=$(sha "$out/$t/a/$p")
      b=$(sha "$out/$t/b/$p")
      if [ "$a" = "$b" ]; then
        echo "$a  $p (linux/amd64 static, built twice, identical)"
      else
        echo "MISMATCH  $p: $a vs $b"
        status=1
      fi
    done
    echo
  done
} >"$record.tmp"

mv "$record.tmp" "$record"
cat "$record"
exit "$status"
